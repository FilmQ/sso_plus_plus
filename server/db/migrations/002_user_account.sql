-- Infrastructure table, not one of the 19 report tables (docs/DECISIONS.md, D-003).
-- It keeps the login accounts. The report has no login use case (07-open-questions.md, item 1).
-- Migration 001 is docs/spec/database/schema.sql, without changes.
-- pgcrypto gives crypt() and gen_salt() for the bcrypt password hash.
CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE UserAccount (
  account_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  role varchar(20) NOT NULL CHECK (role IN ('USER', 'OFFICER', 'CONSULTANT')),
  login_name varchar(120) NOT NULL UNIQUE,
  password_hash varchar(200) NOT NULL,
  insured_id integer REFERENCES InsuredPerson (insured_id),
  officer_id integer REFERENCES EvaluationOfficer (officer_id),
  consultant_id integer REFERENCES Consultant (consultant_id),
  created_at timestamp NOT NULL,
  CHECK (
    (role = 'USER' AND insured_id IS NOT NULL AND officer_id IS NULL AND consultant_id IS NULL) OR
    (role = 'OFFICER' AND officer_id IS NOT NULL AND insured_id IS NULL AND consultant_id IS NULL) OR
    (role = 'CONSULTANT' AND consultant_id IS NOT NULL AND insured_id IS NULL AND officer_id IS NULL)
  )
);
